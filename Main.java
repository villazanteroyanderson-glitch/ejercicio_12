void main() {

            System.out.println("Con FOR:");
            for (int i = 1; i <= 100; i++) {
                System.out.println(i);
            }

            System.out.println("Con WHILE:");
            int j = 1;
            while (j <= 100) {
                System.out.println(j);
                j++;
            }

            System.out.println("Con DO-WHILE:");
            int k = 1;
            do {
                System.out.println(k);
                k++;
            } while (k <= 100);
        }
